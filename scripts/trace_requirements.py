#!/usr/bin/env python3
"""Generate docs/REQUIREMENTS.md from docs/requirements.toml and the latest pytest evidence.

    python -m pytest            # writes build/test-results/requirements.json
    python scripts/trace_requirements.py

Status meanings:
* Tested — at least one test tagged with the requirement ran and every tagged test passed.
* Failing — a tagged test failed in the last run.
* No automated test — implemented or documented, but not covered by a tagged test (see the notes column).
"""

from __future__ import annotations

import json
import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTES = {
    "REL-05": "Verified: release-workflow dry run built and self-tested the frozen application on Windows, macOS and Linux; local Linux build and .deb install (see docs/TEST_REPORT.md).",
    "SYN-02": "Google Drive OAuth/API tested with a mocked HTTP session only; no live account was used.",
    "AI-02": "External providers tested with an injected transport only; no live API calls were made.",
    "UX-06": "Contrast is checked automatically; full screen-reader testing has not been performed.",
    "TPL-01": "Fifteen templates (twelve classic plus three graphical) are distinct layout systems.",
    "PRF-19": "Verified manually: the preliminary profile (delivered separately, not in the ZIP) imports as 73 "
              "records, every fact awaiting confirmation; the release scan rejects personal strings.",
    "REL-02": "See docs/TEST_REPORT.md.",
    "STU-03": "Partial: per-resume wording is stored as approved claims and labelled apart from profile "
              "statements; a separate Guided/Advanced mode switch is not implemented.",
    "UX-03": "Checked manually: Studio has Preview / Content & claims / Checks panels beside the settings; "
             "Opportunities shows requirements beside the analysis.",
    "UX-07": "Partial: navigation, page texts and notices are centralised in ris/strings.py, but many widget "
             "labels are inline and dates use a fixed English format rather than the system locale.",
}


def main() -> int:
    reqs = tomllib.loads((ROOT / "docs" / "requirements.toml").read_text(encoding="utf-8"))["req"]
    ev_path = ROOT / "build" / "test-results" / "requirements.json"
    evidence: dict[str, list[dict]] = json.loads(ev_path.read_text(encoding="utf-8")) if ev_path.exists() else {}
    rows = []
    counts: Counter[str] = Counter()
    for r in reqs:
        tests = evidence.get(r["id"], [])
        if not tests:
            status = "No automated test"
        elif all(t["outcome"] == "passed" for t in tests):
            status = "Tested"
        else:
            status = "Failing"
        counts[status] += 1
        names = sorted({t["test"].split("::")[-1] for t in tests})
        rows.append((r["id"], r["priority"], r["area"], r["text"], status, names, NOTES.get(r["id"], "")))
    out = ["# Requirements traceability", "",
           "Generated by `scripts/trace_requirements.py` from `docs/requirements.toml` and the last test run "
           f"(`build/test-results/requirements.json`{'' if ev_path.exists() else ' — not found'}).", "",
           f"**{len(rows)} requirements:** " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())), "",
           "| ID | P | Area | Requirement | Status | Evidence (tests) | Notes |", "|---|---|---|---|---|---|---|"]
    for rid, pri, area, text, status, names, note in rows:
        ev = "<br>".join(f"`{n}`" for n in names[:4]) + (f"<br>…and {len(names) - 4} more" if len(names) > 4 else "")
        out.append(f"| {rid} | {pri} | {area} | {text.replace('|', '/')} | {status} | {ev} | {note} |")
    (ROOT / "docs" / "REQUIREMENTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"docs/REQUIREMENTS.md written: {dict(counts)}")
    return 1 if counts.get("Failing") else 0


if __name__ == "__main__":
    sys.exit(main())
